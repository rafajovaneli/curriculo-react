import fs from "fs";
import path from "path";

const srcDir = __dirname;

const sourceFiles = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return sourceFiles(full);
    return /\.js$/.test(entry.name) && !/\.test\.js$/.test(entry.name)
      ? [full]
      : [];
  });

describe("icons.css (generated by `npm run icons`)", () => {
  const css = fs.readFileSync(path.join(srcDir, "styles", "icons.css"), "utf8");
  const source = sourceFiles(srcDir)
    .map((file) => fs.readFileSync(file, "utf8"))
    .join("\n");

  test("has a rule for every fa-* icon used in the code", () => {
    const used = new Set(
      [...source.matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)].map((m) => m[1])
    );
    ["chevron-up", "chevron-down"].forEach((name) => used.add(name));
    used.delete("chevron");

    const missing = [...used].filter(
      (name) => name !== "spin" && !css.includes(`.fa-${name}{`)
    );

    expect(missing).toEqual([]);
  });

  test("does not ship icons that nothing uses", () => {
    const defined = [...css.matchAll(/^\.fa-([a-z0-9-]+)\{--fa-icon/gm)].map(
      (m) => m[1]
    );
    const unused = defined.filter(
      (name) =>
        !source.includes(`fa-${name}`) && !["chevron-up", "chevron-down"].includes(name)
    );

    expect(unused).toEqual([]);
  });
});
