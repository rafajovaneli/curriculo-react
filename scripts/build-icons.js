#!/usr/bin/env node
/*
 * Generates src/styles/icons.css with ONLY the Font Awesome icons the code uses.
 *
 * Why: importing all.css ships ~2000 icon rules and makes the browser download
 * ~277 KB of webfonts for about 50 icons. Here every icon is a small SVG used as
 * a CSS mask, so the existing markup (<i className="fas fa-envelope">), dynamic
 * class names, colors (currentColor) and animations keep working unchanged.
 *
 * Run `npm run icons` after adding or removing an icon. The unit test fails if
 * src/styles/icons.css is missing a used icon.
 */
const fs = require("fs");
const path = require("path");
const yaml = require("js-yaml");

const root = path.resolve(__dirname, "..");
const fa = path.join(root, "node_modules", "@fortawesome", "fontawesome-free");
const MODIFIERS = new Set(["spin"]);
const STYLE_CLASS = { fas: "solid", far: "regular", fab: "brands" };

const walk = (dir) =>
  fs.readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) return walk(full);
    return /\.js$/.test(entry.name) && !/\.test\.js$/.test(entry.name) ? [full] : [];
  });

const source = walk(path.join(root, "src"))
  .map((file) => fs.readFileSync(file, "utf8"))
  .join("\n");

// Preferred style per icon when the code writes "fab fa-java", "fas fa-leaf"...
const styleOf = {};
for (const [, cls, name] of source.matchAll(/\b(fas|far|fab)\s+fa-([a-z0-9-]*[a-z0-9])\b/g)) {
  styleOf[name] = STYLE_CLASS[cls];
}

// Every fa-* token, plus the ones built from templates (fa-chevron-${...}).
const tokens = new Set(
  [...source.matchAll(/\bfa-([a-z0-9]+(?:-[a-z0-9]+)*)/g)].map((m) => m[1])
);
["chevron-up", "chevron-down"].forEach((name) => tokens.add(name));
tokens.forEach((name) => {
  if (name === "chevron" || name.endsWith("-")) tokens.delete(name);
});

const meta = yaml.load(
  fs.readFileSync(path.join(fa, "metadata", "icons.yml"), "utf8")
);
const canonical = {};
for (const [name, info] of Object.entries(meta)) {
  canonical[name] = name;
  for (const alias of (info.aliases && info.aliases.names) || []) {
    canonical[alias] = name;
  }
}

const readSvg = (style, name) => {
  const file = path.join(fa, "svgs", style, `${name}.svg`);
  if (!fs.existsSync(file)) return null;
  const svg = fs.readFileSync(file, "utf8");
  const viewBox = svg.match(/viewBox="0 0 (\d+) (\d+)"/);
  const d = svg.match(/<path d="([^"]+)"/);
  if (!viewBox || !d) throw new Error(`Unexpected SVG format: ${file}`);
  return { width: +viewBox[1], height: +viewBox[2], d: d[1] };
};

const rules = [];
const missing = [];
[...tokens].sort().forEach((token) => {
  if (MODIFIERS.has(token)) return;
  const name = canonical[token] || token;
  const styles = [styleOf[token], "solid", "brands", "regular"].filter(Boolean);
  let icon = null;
  for (const style of styles) {
    icon = readSvg(style, name);
    if (icon) break;
  }
  if (!icon) {
    missing.push(token);
    return;
  }
  const svg =
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${icon.width} ${icon.height}'>` +
    `<path d='${icon.d}'/></svg>`;
  const uri = svg.replace(/</g, "%3C").replace(/>/g, "%3E").replace(/#/g, "%23");
  const width = +(icon.width / icon.height).toFixed(4);
  rules.push(
    `.fa-${token}{--fa-icon:url("data:image/svg+xml,${uri}");--fa-w:${width}em}`
  );
});

if (missing.length) {
  console.error("Icons not found in Font Awesome Free:", missing.join(", "));
  process.exit(1);
}

const css = `/* GENERATED by scripts/build-icons.js - do not edit by hand. Run \`npm run icons\`.
   Only the Font Awesome Free icons used in src/ (CC BY 4.0, https://fontawesome.com/license/free). */
.fas,
.far,
.fab {
  display: inline-block;
  font-style: normal;
  line-height: 1;
  text-rendering: auto;
}

.fas::before,
.far::before,
.fab::before {
  content: "";
  display: inline-block;
  width: var(--fa-w, 1em);
  height: 1em;
  vertical-align: top;
  background-color: currentColor;
  -webkit-mask: var(--fa-icon) center / contain no-repeat;
  mask: var(--fa-icon) center / contain no-repeat;
}

.fa-spin {
  animation: fa-spin 2s linear infinite;
}

@keyframes fa-spin {
  to {
    transform: rotate(360deg);
  }
}

${rules.join("\n")}
`;

fs.writeFileSync(path.join(root, "src", "styles", "icons.css"), css);
console.log(`icons.css: ${rules.length} icons, ${(css.length / 1024).toFixed(1)} KB`);
